"""给模型的提示词。

放在这里而不是 `main.py`：`main.py` 顶层 import astrbot，本地跑不了单测，而
提示词里那些**硬性的输出格式与反端水约定**是要被测试钉住的。

最重要的两条，写给模型的写实约束：

1. **字段白名单。** 掌瓦对局列表里没有 ADR、没有 KAST、没有经济、没有攻防回合。
   必须明确告诉模型「这些没有」，否则它一定会照着 CS2 那套指标编——
   编出来的分析看着很专业，实际一个字都对不上。这一步是爱完美踩过的坑：
   模型被一堆它「知道」的 FPS 术语带跑，输出与数据源严重脱轨。

2. **地图名与特工名用接口给的中文原文。** 我们不维护翻译表，
   接口自己返回本地化名称，照抄即可。换成自造译名只会造出错的名字。
"""

from __future__ import annotations

__all__ = [
    "FIELD_ALLOWLIST",
    "FLUFF_WORDS",
    "SIMULATION_NOTICE",
    "TITLE_PREFIX",
    "match_prompt",
    "pk_prompt",
    "review_prompt",
]

TITLE_PREFIX = "你最近是个"

SIMULATION_NOTICE = "⚠️ 这局是推演出来的，不是真实战绩"

FLUFF_WORDS = (
    "各有千秋",
    "不相上下",
    "势均力敌",
    "难分伯仲",
    "都很强",
    "继续努力",
    "加油",
    "都有提升空间",
    "提升空间很大",
)

# 对局列表**实际提供**的维度。写进提示词，让模型知道边界在哪儿。
AVAILABLE = (
    "胜负（result_title）",
    "击杀/死亡/助攻（kda 字符串）",
    "场均战斗评分 ACS（score_avg）",
    "地图名（used_map.name，接口已本地化）",
    "使用特工名（hero_name，接口已本地化）",
    "本局双方回合数（round_won / round_fail）",
)

# 同一份数据**不提供**的维度。这一段比上面那段重要。
UNAVAILABLE = (
    "ADR（场均伤害）",
    "KAST",
    "经济与 eco 局",
    "攻防半场分开的回合数",
    "命中率（头/身/腿分布）",
    "武器使用明细",
    "队友与其账号信息",
)

FIELD_ALLOWLIST = f"""\
可以用的数据：{"、".join(AVAILABLE)}。
这份数据里**没有**，因此不许提到：{"、".join(UNAVAILABLE)}。
"""

_REVIEW_SKELETON = f"""\
{TITLE_PREFIX}<称号>

<两三句总评：这份数据说明了什么>

打得好：<点到具体的地图或特工与数据，说清他真正靠什么赢>
问题：<点出数据里最扎眼的一处短板>
建议：<一条今天就能照做的具体做法>"""


def review_prompt(data: str) -> str:
    """锐评的提示词。数据是 `aiva.stats.近况文本` 的输出。"""
    return (
        "下面是一个玩家自己的《无畏契约》国服近期战绩统计。请写一段锐评，"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{_REVIEW_SKELETON}\n\n"
        "硬要求：\n"
        f"- 第一行必须以「{TITLE_PREFIX}」开头，后面接不超过 18 字的称号；称号里要带上"
        "他的段位、招牌特工或常打的地图。\n"
        "- **段位只能照抄数据里的「当前段位」那一句**，一个字都不许改、"
        "不许推断、不许拿别的段位代替。数据里如果写了「接口没给」，"
        "称号里就完全不出现段位——编一个段位比不写段位恶劣得多，"
        "它会让玩家以为自己真的是那一个段。\n"
        "- 称号要贴着数据说，别写成「枪法准」这类放在谁身上都成立的废话。\n"
        "- 后面四个小标题原样保留（打得好／问题／建议），每段一句话。\n"
        "- 全文至少出现 3 个具体数字（胜率、KDA、ACS、回合差之类），"
        "不许通篇形容词。\n"
        "- 「问题」那一段必须指向数据里的具体一项。"
        "在《无畏契约》里最能说的是**场均死亡**：回合制游戏死了就退场这一回合，"
        "死亡偏高多半是进点太早、没人架枪就露身位，要说清是哪一种。"
        "不许写「多练枪」「注意配合」这种没落到数据上的话。\n"
        f"- 禁止出现这些端水词：{'、'.join(FLUFF_WORDS)}。\n"
        f"- **只说数据支撑得住的话。**{FIELD_ALLOWLIST}\n"
        "  具体来说：没有命中率就不要谈「爆头率高不高」；没有经济和 eco 数据就"
        "不要分析某一局的经济决策；没有队友信息就不要揣测「队友不配合」。"
        "宁可少说一句，也不要编一句——编出来的分析比没有分析更糟，"
        "它看起来很有道理。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」，不要客套。\n"
        "- 全文 180 到 260 字。\n\n"
        "数据：\n"
        f"{data}"
    )


def match_prompt(setup: str) -> str:
    """「开一局」的提示词。`setup` 是 `aiva.match.setup_text` 的输出。"""
    return (
        "下面是一局《无畏契约》竞技模式的**推演设定**——数字是随机"
        "生成的，不是真实战绩。请你根据这局设定写一段赛后复盘。\n\n"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{SIMULATION_NOTICE}\n"
        "经过：<两三句：这一局是怎么打的，节奏怎么走>\n"
        "亮点：<点出这局设定里最漂亮的一处，带具体数字>\n"
        "问题：<点出这局设定里最难看的一处，带具体数字>\n"
        "复盘：<一句下次该怎么做>\n\n"
        "硬要求：\n"
        f"- 第一行必须是「{SIMULATION_NOTICE}」，原样保留，不许改写、不许省略。\n"
        "- 后面四个小标题原样保留（经过／亮点／问题／复盘），每段一到两句。\n"
        "- 每一段都要落到设定里的具体内容上：地图、特工、比分、击杀、死亡、"
        "爆头率、ACS、下包拆包、残局，随便挑着用。\n"
        "- 「亮点」和「问题」各必须出现设定里的至少一个数字。\n"
        "- 《无畏契约》是回合制，**输的一方照样可能打出高 ACS 与高击杀**——"
        "「虽败犹荣」在这里很常见。不要因为输了就把整局写成一无是处，"
        "也不要因为赢了就无视难看的数据。\n"
        "- **只说数据支撑得住的话**。设定里没有的依据不要编：没写经济就别讲「eco "
        "局没打出优势」，没写队友就别揣测队友怎么想。宁可少说一句，也不要编"
        "一句——编出来的复盘看起来很有道理。\n"
        "- 不要复述设定原文，不要「首先／其次／总而言之」，不要客套。\n"
        "- 全文 150 到 220 字。\n\n"
        "这局的设定：\n"
        f"{setup}"
    )


def pk_prompt(
    a_name: str,
    b_name: str,
    contrast: str,
    advantage: str,
    a_data: str,
    b_data: str,
) -> str:
    """两人 PK 的提示词。

    `contrast` 与 `advantage` 都由 `stats.对比要点` 算好——模型不做比较，只做解说。
    """
    return (
        f"下面是 {a_name} 和 {b_name} 的《无畏契约》国服近期战绩。"
        "逐项对比**已经替你算好了**，你的任务只是解说和打分："
        "不要重算、不要推翻对比结论、不要两边都给好评。\n\n"
        "严格按下面的格式输出，不要前言、不要标题、不要编号：\n\n"
        f"{a_name} <分数>\n"
        f"{b_name} <分数>\n"
        "胜者：<名字>\n"
        "逐项：<挑差异最大的 3 项，写成「项名：谁占优（谁的数字 对 谁的数字）」>\n"
        "互损：<两三句>\n\n"
        "硬要求：\n"
        "- 分数取 0-100 的整数，分差要跟两人的实际差距相符。"
        "两人本来就接近时不必为了制造对立拉开分数。\n"
        f"- 胜者那一行写分数更高的那个人，名字从这里挑：{a_name} 或 {b_name}。\n"
        "- 占优项更多的一方不一定分数更高，一切从实际出发。"
        f"占优项数仅供参考：{advantage}\n"
        "- 「逐项」那行必须写出项名与双方数字。\n"
        "- 「互损」主要攻击输的一方最难看的那一项，必须带上具体数字或特工名、"
        "地图名；赢的一方顺带攻击一下就行，不要两边都重点攻击。\n"
        f"- 禁止出现这些端水词：{'、'.join(FLUFF_WORDS)}。\n"
        f"- **只说数据支撑得住的话。**{FIELD_ALLOWLIST}\n"
        "  没有命中率就别讲谁更准，没有经济数据就别讲谁 eco 打得好。\n"
        "- 「互损」至少 90 字，不许一句话打发。\n"
        "- 不要复述数据原文，不要「首先／其次／总而言之」。\n\n"
        "已算好的逐项对比：\n"
        f"{contrast}\n\n"
        f"【{a_name}】原始数据\n{a_data}\n\n【{b_name}】原始数据\n{b_data}"
    )
